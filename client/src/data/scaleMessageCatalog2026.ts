function buildMessages(
  instrument: string,
  purpose: string,
  ageRange: string,
  logic: ScoreLogic,
) {
  if (logic === "higher_worse") {
    return {
      instruction:
        `Responda todos os itens do ${instrument} considerando sinais observados ` +
        `na faixa etária ${ageRange}. Marque frequência ou intensidade com base ` +
        `em exemplos reais e no período definido pelo manual.`,
      infoBox:
        `Finalidade: ${purpose}. Pontuações mais elevadas geralmente representam ` +
        `maior carga de sinais, mas a interpretação deve respeitar versão, ` +
        `respondente, normas e pontos de corte oficiais.`,
      resultMessages: {
        favorable:
          "Resultado em faixa de baixa carga de sinais. Não exclui condição clínica " +
          "quando houver história, prejuízo funcional ou observação médica discordante.",
        borderline:
          "Resultado intermediário ou limítrofe. Confirmar duração, pervasividade, " +
          "contexto, prejuízo funcional e concordância entre família, escola e " +
          "avaliação clínica.",
        altered:
          "Resultado elevado para os sinais rastreados. Recomenda-se avaliação clínica " +
          "dirigida e análise de diagnósticos diferenciais; a escala isoladamente não " +
          "confirma diagnóstico.",
        important:
          "Resultado muito elevado ou com itens críticos. Priorizar avaliação clínica, " +
          "segurança e impacto funcional, registrando os comportamentos por extenso e " +
          "as fontes de informação.",
      },
    };
  }
  if (logic === "higher_better") {
    return {
      instruction:
        `Registre no ${instrument} as habilidades, capacidades ou aspectos de qualidade ` +
        `de vida realmente observados para a faixa etária ${ageRange}. Utilize exemplos ` +
        `funcionais e siga as regras do manual aplicável.`,
      infoBox:
        `Finalidade: ${purpose}. Pontuações mais altas geralmente representam melhor ` +
        `desempenho, funcionalidade ou qualidade de vida, desde que calculadas pela ` +
        `versão e pelas normas oficiais.`,
      resultMessages: {
        favorable:
          "Resultado global em faixa favorável para a referência utilizada. Manter " +
          "acompanhamento e descrever eventuais discrepâncias entre domínios.",
        borderline:
          "Resultado parcialmente adequado ou heterogêneo. Reavaliar áreas frágeis e " +
          "fatores contextuais capazes de influenciar o desempenho.",
        altered:
          "Resultado abaixo do esperado em um ou mais domínios. Correlacionar com " +
          "história, exame, funcionalidade e avaliações complementares.",
        important:
          "Resultado marcadamente abaixo do esperado ou perda funcional relevante. " +
          "Priorizar investigação, intervenção e seguimento estruturado, sem inferir " +
          "etiologia apenas pelo escore.",
      },
    };
  }
  if (logic === "classification") {
    return {
      instruction:
        `Classifique o paciente no ${instrument} conforme os descritores oficiais ` +
        `aplicáveis à faixa etária ${ageRange}. Registre exemplos funcionais que ` +
        `justifiquem a categoria escolhida.`,
      infoBox:
        `Finalidade: ${purpose}. Trata-se de sistema classificatório ou exame ` +
        `estruturado; o nível deve ser descrito por extenso e não convertido em ` +
        `diagnóstico ou prognóstico isoladamente.`,
      resultMessages: {
        favorable:
          "Categoria associada a menor limitação ou menor gravidade no sistema " +
          "utilizado. Documentar capacidades, ajudas necessárias e condições em que " +
          "o desempenho foi observado.",
        borderline:
          "Categoria intermediária. Verificar variações por ambiente, fadiga, dor, " +
          "cooperação, tecnologia assistiva ou apoio de terceiros.",
        altered:
          "Categoria associada a limitação ou alteração relevante. Integrar o achado " +
          "ao exame clínico, às metas funcionais e ao plano terapêutico.",
        important:
          "Categoria de maior limitação, gravidade ou risco no sistema utilizado. " +
          "Priorizar segurança, suporte multidisciplinar e descrição objetiva das " +
          "necessidades.",
      },
    };
  }
  return {
    instruction:
      `Aplicar o ${instrument} conforme o manual oficial, utilizando materiais ` +
      `padronizados, regras de início, inversão e interrupção, além das normas ` +
      `correspondentes à faixa etária ${ageRange}.`,
    infoBox:
      `Finalidade: ${purpose}. A direção do escore e sua interpretação dependem da ` +
      `versão, das subescalas, dos escores padronizados, dos percentis, dos intervalos ` +
      `de confiança e da validade do protocolo.`,
    resultMessages: {
      favorable:
        "Resultado dentro da faixa esperada nas normas ou critérios utilizados. " +
        "Descrever o perfil por domínios e evitar reduzir a conclusão a um único " +
        "escore global.",
      borderline:
        "Resultado limítrofe ou perfil discrepante. Revisar validade do protocolo, " +
        "comportamento durante a aplicação, linguagem, escolaridade, atenção e " +
        "intervalos de confiança.",
      altered:
        "Resultado clinicamente relevante ou abaixo do esperado segundo o manual. " +
        "Correlacionar com funcionalidade, história, observação clínica e instrumentos " +
        "convergentes.",
      important:
        "Resultado marcadamente discrepante ou protocolo potencialmente inválido. " +
        "Não concluir diagnóstico antes de revisar administração, correção, normas e " +
        "fatores sensoriais, motores, emocionais e socioculturais.",
    },
  };
}
